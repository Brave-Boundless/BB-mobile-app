/// <reference types="node" />
/**
 * Generates the SQL migration that loads the 15 Rule Cards into `public.rules`.
 *
 * content/bb-rule-cards.json is the editable source. The database copy is
 * derived from it and must never be edited by hand.
 *
 *   npm run rules:sql          write a new migration if the JSON changed
 *   npm run rules:sql -- --check   exit 1 if the latest rules migration is stale (CI)
 *
 * Migrations are append-only once applied, so a copy change produces a new
 * `<timestamp>_sync_rules.sql` file rather than editing the old one. The SQL
 * is an upsert, so applying any rules migration leaves the table matching it.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import type { RuleCardsFile } from '../src/content/types';

const ROOT = resolve(__dirname, '..');
const JSON_PATH = join(ROOT, 'content', 'bb-rule-cards.json');
const MIGRATIONS_DIR = join(ROOT, 'supabase', 'migrations');
const RULES_MIGRATION_SUFFIX = '_rules.sql';

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function buildRulesSql(file: RuleCardsFile): string {
  const rows = [...file.rules]
    .sort((a, b) => a.number - b.number)
    .map((r) =>
      [
        String(r.number),
        String(r.part),
        sqlString(r.title),
        sqlString(r.chapter),
        sqlString(r.why_it_matters),
        sqlString(r.drills.five_minute),
        sqlString(r.drills.uncomfortable),
        sqlString(r.drills.daily),
        sqlString(r.scorecard),
        sqlString(r.mantra),
      ].join(',\n    '),
    )
    .map((row) => `  (\n    ${row}\n  )`)
    .join(',\n');

  return `-- GENERATED by scripts/generate-rules-migration.ts — do not edit by hand.
-- Source: content/bb-rule-cards.json
-- ${file.source}

insert into public.rules
  (id, part, title, chapter, why, drill_5min, drill_uncomfortable, drill_daily, scorecard, mantra)
values
${rows}
on conflict (id) do update set
  part                = excluded.part,
  title               = excluded.title,
  chapter             = excluded.chapter,
  why                 = excluded.why,
  drill_5min          = excluded.drill_5min,
  drill_uncomfortable = excluded.drill_uncomfortable,
  drill_daily         = excluded.drill_daily,
  scorecard           = excluded.scorecard,
  mantra              = excluded.mantra;
`;
}

export function latestRulesMigration(dir = MIGRATIONS_DIR): string | undefined {
  return readdirSync(dir)
    .filter((f) => f.endsWith(RULES_MIGRATION_SUFFIX))
    .sort()
    .at(-1);
}

function timestamp(d = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}${p(d.getUTCHours())}${p(d.getUTCMinutes())}${p(d.getUTCSeconds())}`;
}

function main(argv: string[]): number {
  const check = argv.includes('--check');
  const file = JSON.parse(readFileSync(JSON_PATH, 'utf8')) as RuleCardsFile;
  const sql = buildRulesSql(file);
  const latest = latestRulesMigration();
  const current = latest ? readFileSync(join(MIGRATIONS_DIR, latest), 'utf8') : undefined;

  if (current === sql) {
    console.log(`rules: up to date (${latest})`);
    return 0;
  }
  if (check) {
    console.error(
      `rules: ${latest ?? 'no rules migration'} does not match content/bb-rule-cards.json. Run \`npm run rules:sql\`.`,
    );
    return 1;
  }
  const name = `${timestamp()}_${latest ? 'sync' : 'seed'}${RULES_MIGRATION_SUFFIX}`;
  writeFileSync(join(MIGRATIONS_DIR, name), sql);
  console.log(`rules: wrote supabase/migrations/${name}`);
  return 0;
}

if (require.main === module) {
  process.exit(main(process.argv.slice(2)));
}
